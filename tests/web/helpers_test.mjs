import assert from 'node:assert/strict';
import {contentRect, normalizedPoint, normalizeWheel, protocolKey, utf8Chunks, parseFrame} from '../../web/app.mjs';
const rect = contentRect(1000, 1000, 1600, 900);
assert.deepEqual(rect, {left: 0, top: 218.75, width: 1000, height: 562.5});
assert.equal(normalizedPoint(500, 10, rect), null);
assert.deepEqual(normalizedPoint(500, 500, rect), {x: .5, y: .5});
assert.deepEqual(normalizedPoint(1200, -10, rect, true), {x: 1, y: 0});
assert.deepEqual(normalizedPoint(1000, 781.25, rect), {x: 1, y: 1});
assert.equal(contentRect(0, 100, 100, 100), null);
assert.equal(normalizedPoint(NaN, 0, rect), null);
assert.equal(normalizeWheel(0, 100, 0).vertical, -1);
assert.equal(normalizeWheel(0, 3, 1).vertical, -1);
assert.equal(normalizeWheel(0, 1, 2).vertical, -10);
for (const [code, key] of [['KeyA','A'], ['ControlRight','RightCtrl'], ['NumpadEnter','KeypadEnter'],
    ['ArrowLeft','Left'], ['F12','F12'], ['Digit3','Digit3'], ['Quote','Apostrophe']]) assert.equal(protocolKey(code), key);
assert.equal(protocolKey('keyCode'), null);
const text = 'äöüÄÖÜß 日本 🙂'.repeat(100), chunks = utf8Chunks(text);
assert.equal(chunks.join(''), text);
for (const chunk of chunks) assert.ok(new TextEncoder().encode(chunk).length <= 256);
const data = new ArrayBuffer(31), h = new DataView(data);
h.setUint32(0, 0x524d4a50); h.setUint16(4, 1); h.setUint16(6, 1); h.setBigUint64(8, 42n);
h.setUint32(16, 640); h.setUint32(20, 480); h.setUint32(24, 3);
assert.equal(parseFrame(data).id, '42');
h.setBigUint64(8, 0xffffffffffffffffn);
assert.equal(parseFrame(data).id, '18446744073709551615');
for (const length of [0, 10, 27, 28, 30]) assert.throws(() => parseFrame(data.slice(0,length)));
h.setUint32(24, 90000000); assert.throws(() => parseFrame(data));
h.setUint32(24, 3); h.setUint16(4, 2); assert.throws(() => parseFrame(data));
console.log('Web JS helpers passed: letterboxing, capture, wheel, keys, UTF-8, malformed frames.');
